function slugPart(value: string) {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64);
}

function exportTimestamp(date: Date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  const hours = String(date.getHours()).padStart(2, "0");
  const minutes = String(date.getMinutes()).padStart(2, "0");
  const seconds = String(date.getSeconds()).padStart(2, "0");
  const milliseconds = String(date.getMilliseconds()).padStart(3, "0");
  return `${year}-${month}-${day}-${hours}${minutes}${seconds}-${milliseconds}`;
}

export function uniquePngName(parts: Array<string | undefined>, exportedAt = new Date()) {
  const readable = parts.map((part) => slugPart(part ?? "")).filter(Boolean);
  return [...readable, "exported", exportTimestamp(exportedAt)].join("-") + ".png";
}
